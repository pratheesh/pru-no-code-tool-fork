@needs_ti
def test_two_instances_assemble():
    asm = program([call("R4"), call("R7")])
    with tempfile.TemporaryDirectory(prefix="gw_") as wd:
        elf_cosim.compile_asm(asm, wd, "two")


def test_branch_labels_are_macro_local():
    macro = macro_text()
    labels = re.findall(r"^(sg_\w+)(\??):", macro, re.M)
    assert labels, "no labels found"
    assert all(q == "?" for _n, q in labels), labels
    for ref in re.findall(r"\b(?:qbeq|qbne|qba)\s+(sg_\w+\??)", macro):
        assert ref.endswith("?"), ref


# ---------------------------------------------------------------------------
# mailbox
# ---------------------------------------------------------------------------

class _Idle:
    def tick(self, _cycle, _gpo):
        return 0


def mailbox_init(write_ptr, read_ptr, payload_words):
    """Instructions that lay the mailbox into data memory: pointers, slot 0 = payload, the
    other slots filled with FILL (a .data image is not loaded at this offset)."""
    words = [write_ptr, read_ptr] + list(payload_words) +         [FILL * 0x01010101] * (SLOT_BYTES // 4 * (SLOTS - 1))
    lines = ["    ldi32   R11, %d" % MB_BASE]
    for w in words:
        lines += ["    ldi32   R10, %d" % w, "    sbbo    &R10, R11, 0, 4", "    add     R11, R11, 4"]
    return lines


def run_mailbox(write_ptr, read_ptr, payload_words, **call_kw):
    asm = program(mailbox_init(write_ptr, read_ptr, payload_words) + [call(**call_kw)])
    holder = {}
    with tempfile.TemporaryDirectory(prefix="gw_") as wd:
        elf = elf_cosim.compile_asm(asm, wd, "mb")
        res = elf_cosim.run_elf_closed_loop(
            elf, _Idle(), max_steps=5000,
            on_step=lambda c, g, i, sim: holder.setdefault("sim", sim))
    assert res.halted, "PRU did not halt"
    mem = holder["sim"].memory_read(MB_BASE, 8 + SLOTS * SLOT_BYTES)
    return res.registers, struct.unpack_from("<II", mem, 0), mem


PAYLOAD = [0xA0000000 + i for i in range(SLOT_BYTES // 4)]


@needs_ti
def test_pending_command_advances_the_read_pointer_and_keeps_r30_r31_clean():
    regs, (wr, rd), _mem = run_mailbox(1, 0, PAYLOAD)
    assert rd == 1, "read pointer (mailbox word 1) must advance past the consumed slot"
    assert regs[30] == 0, "payload data reached R30: %#x" % regs[30]
    assert regs[31] == 0, "payload data reached R31: %#x" % regs[31]


@needs_ti
def test_rx_publish_writes_only_the_status_word_into_the_slot():
    regs, _ptrs, mem = run_mailbox(0, 0, [FILL * 0x01010101] * (SLOT_BYTES // 4))
    slot = mem[8:8 + SLOT_BYTES]
    assert struct.unpack_from("<I", slot, 0)[0] == regs[4] != FILL * 0x01010101
    assert slot[4:] == bytes([FILL]) * (SLOT_BYTES - 4), \
        "bytes after the status word were overwritten with other registers"
