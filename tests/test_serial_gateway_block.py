"""Industrial serial gateway macro: local labels, mailbox consume and RX publish.

The macro is generated by industrial_serial_gateway_block.syscfg.js, assembled with
clpru and (for the mailbox arms) run on the TI pru-simulator against a mailbox laid
out in PRU data memory: word 0 = host write pointer, word 1 = PRU read pointer,
slots from base + 8.
"""
import json
import os
import re
import struct
import subprocess
import sys
import tempfile

import pytest

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
sys.path.insert(0, os.path.join(ROOT, "scripts", "sim"))
import elf_cosim  # noqa: E402

OPCODE = "m_serial_gateway_run"

_EMIT = r"""
const {loadBlockModule} = require(process.argv[1] + '/scripts/dual_oracle_harness.js');
const m = loadBlockModule('industrial_serial_gateway_block', 'application_specific');
process.stdout.write(m.getMacro('', process.argv[2]));
"""

try:
    elf_cosim.find_pru_simulator()
    elf_cosim.find_clpru()
    _HAVE_TI = True
except RuntimeError:
    _HAVE_TI = False

needs_ti = pytest.mark.skipif(
    not _HAVE_TI, reason="TI pru-simulator (PRU_SIMULATOR_PATH) and/or clpru unavailable")

MB_BASE = 0x400
SLOTS = 4
SLOT_BYTES = 32
FILL = 0xCC


def macro_text():
    out = subprocess.run(["node", "-e", _EMIT, ROOT, OPCODE], capture_output=True,
                         text=True, timeout=60, check=True)
    return out.stdout


def call(status="R4", slot_bytes=SLOT_BYTES, shared=0, dir_pin=4):
    # STATUS, TX_DATA_REG, TX_CMD_REG, then the 23 macro parameters in call order
    args = [status, "R5", "R6", 0, 1666, 0, dir_pin, 50, 200, MB_BASE, 2, slot_bytes, shared,
            0, 16, 1, 16, 200, 20, 170, 0, 1, 64, 1, 1, 200]
    return "    %s %s" % (OPCODE, ", ".join(str(a) for a in args))


def program(calls, data=""):
    return "\n".join([
        "    .asg R28, TEMP_REG1", "    .asg R29, TEMP_REG2",
        "    .asg R26, TEMP_REG3", "    .asg R27, TEMP_REG4",
        macro_text(), "    .text", "    .global main", "main:", *calls, "    halt", data, ""])


