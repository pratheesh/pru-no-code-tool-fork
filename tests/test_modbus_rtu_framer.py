"""Modbus RTU framer: frame check, CRC lookup and character-layer setup.

The macro is generated by modbus_rtu_framer.syscfg.js, assembled with clpru and
run on the TI pru-simulator.  The frame-check tail of the macro (everything from
``mb_frame_check?`` on) is reached directly with a frame already in the buffer, so
the CRC lookup, status selection and address filter run exactly as generated.
The character-layer init is run on its own against the simulator's peripheral
interface registers.

Expected CRC values come from a bit-serial CRC-16/MODBUS written below from the
definition (poly 0xA001 reflected, init 0xFFFF), not from the block's table.
"""
import os
import re
import subprocess
import sys
import tempfile

import pytest

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
sys.path.insert(0, os.path.join(ROOT, "scripts", "sim"))
import elf_cosim  # noqa: E402

BLOCK_JS = os.path.join(
    ROOT, ".metadata/sysconfig/.meta/pru_blocks/application_specific/modbus_rtu_framer.syscfg.js")
OPCODE = "m_modbus_rtu_rx_frame_pru0_ch0_1x"

_EMIT = r"""
const {loadBlockModule} = require(process.argv[1] + '/scripts/dual_oracle_harness.js');
const m = loadBlockModule('modbus_rtu_framer', 'application_specific');
process.stdout.write(JSON.stringify({macro: m.getMacro('', process.argv[2]),
                                     lut: m.getLookUptable({})}));
"""


def emit(op_code=OPCODE):
    import json
    out = subprocess.run(["node", "-e", _EMIT, ROOT, op_code], capture_output=True,
                         text=True, timeout=60, check=True)
    return json.loads(out.stdout)


def crc16_modbus(data):
    crc = 0xFFFF
    for b in data:
        crc ^= b
        for _ in range(8):
            crc = (crc >> 1) ^ 0xA001 if crc & 1 else crc >> 1
    return crc


def with_crc(payload):
    c = crc16_modbus(payload)
    return bytes(payload) + bytes([c & 0xFF, c >> 8])


# ---------------------------------------------------------------------------
# simulator harness
# ---------------------------------------------------------------------------

try:
    elf_cosim.find_pru_simulator()
    elf_cosim.find_clpru()
    _HAVE_TI = True
except RuntimeError:
    _HAVE_TI = False

needs_ti = pytest.mark.skipif(
    not _HAVE_TI, reason="TI pru-simulator (PRU_SIMULATOR_PATH) and/or clpru unavailable")


class _Idle:
    def tick(self, _cycle, _gpo):
        return 0


def _run(asm, name, on_step=None, max_steps=20000):
    with tempfile.TemporaryDirectory(prefix="mb_") as wd:
        elf = elf_cosim.compile_asm(asm, wd, name)
        res = elf_cosim.run_elf_closed_loop(elf, _Idle(), max_steps=max_steps, on_step=on_step)
    assert res.halted, "PRU did not halt"
    return res


def _program(macro, lut, prelude, buf_bytes=None):
    return "\n".join([
        "    .asg R28, TEMP_REG1", "    .asg R29, TEMP_REG2",
        macro, "    .text", "    .global main", "main:", *prelude,
        "    halt", "    .data", "lut .ushort " + lut,
        "buf .byte " + ",".join(str(b) for b in (buf_bytes or [0])), ""])


def check_frame(frame, slave=17, length=None, op_code=OPCODE):
    """Run the generated frame check on `frame`; returns (status, length, crc)."""
    parts = emit(op_code)
    macro = parts["macro"].replace(
        "    ; ===== character layer init", "    qba     mb_frame_check?\n"
        "    ; ===== character layer init", 1)
    assert "qba     mb_frame_check?" in macro
    n = len(frame) if length is None else length
    asm = _program(macro, parts["lut"], [
        "    ldi     R4, 0", "    ldi     R4.b1, %d" % n,
        "    %s R4, %d, 1, 1, buf, lut" % (op_code, slave)], frame)
    reg = _run(asm, "frame").registers[4]
    return reg & 0xFF, (reg >> 8) & 0xFF, reg >> 16


# ---------------------------------------------------------------------------
# frame length check
# ---------------------------------------------------------------------------

@needs_ti
@pytest.mark.parametrize("length", [0, 1, 2, 3])
def test_frame_shorter_than_four_bytes_is_status_3(length):
    status, _n, _crc = check_frame(with_crc([17, 3])[:4], length=length)
    assert status == 3


@needs_ti
def test_four_byte_frame_is_not_reported_short():
    # address + function + CRC: the smallest legal frame
    status, _n, _crc = check_frame(with_crc([17, 3]))
    assert status != 3


def test_store_guard_skips_the_store_only_beyond_the_buffer():
    # PRU compares OP against the register: qblt L, reg, 254 branches when 254 < reg.
    macro = emit()["macro"]
    assert re.search(r"qblt\s+mb_no_store\?,\s*\S+\.b1,\s*254", macro)
